-- 1. TABLA DE USUARIOS / COLABORADORES
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL DEFAULT 'colaborador' CHECK (role IN ('admin', 'lider', 'colaborador')),
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  last_login TIMESTAMPTZ
);

-- 2. TABLA DE OBJETIVOS (Mes / Sprint)
CREATE TABLE IF NOT EXISTS objectives (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  start_date DATE,
  end_date DATE,
  metric_target DOUBLE PRECISION,
  metric_current DOUBLE PRECISION NOT NULL DEFAULT 0,
  metric_unit TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT true,
  hidden_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  hidden_at TIMESTAMPTZ,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 3. TABLA DE RUTINAS DIARIAS (Plantillas recurrentes)
CREATE TABLE IF NOT EXISTS routines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  objective_id BIGINT REFERENCES objectives(id) ON DELETE SET NULL,
  assignee_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  estimated_minutes INTEGER NOT NULL DEFAULT 30,
  due_time TEXT NOT NULL DEFAULT '18:00',
  priority TEXT NOT NULL DEFAULT 'media' CHECK (priority IN ('baja', 'media', 'alta')),
  weekdays TEXT NOT NULL DEFAULT '1,2,3,4,5,6,7',
  active BOOLEAN NOT NULL DEFAULT true,
  hidden_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  hidden_at TIMESTAMPTZ,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 4. TABLA DE TAREAS
CREATE TABLE IF NOT EXISTS tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  objective_id BIGINT REFERENCES objectives(id) ON DELETE SET NULL,
  routine_id BIGINT REFERENCES routines(id) ON DELETE SET NULL,
  routine_date DATE,
  assignee_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  estimated_minutes INTEGER NOT NULL DEFAULT 30,
  status TEXT NOT NULL DEFAULT 'sin_iniciar' CHECK (status IN ('sin_iniciar', 'en_progreso', 'terminada', 'faltante')),
  priority TEXT NOT NULL DEFAULT 'media' CHECK (priority IN ('baja', 'media', 'alta')),
  due_at TIMESTAMPTZ,
  needs_help BOOLEAN NOT NULL DEFAULT false,
  help_note TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT true,
  hidden_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  hidden_at TIMESTAMPTZ,
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_tasks_routine_day
  ON tasks(routine_id, routine_date) WHERE routine_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_tasks_assignee ON tasks(assignee_id);
CREATE INDEX IF NOT EXISTS ix_tasks_objective ON tasks(objective_id);

-- 5. TABLA DE ACTIVIDAD (Bitácora / Auditoría)
CREATE TABLE IF NOT EXISTS activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  user_name TEXT NOT NULL,
  action TEXT NOT NULL,
  entity TEXT NOT NULL,
  entity_id BIGINT,
  summary TEXT NOT NULL,
  details JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 6. POLÍTICAS DE ACCESO ROW LEVEL SECURITY (RLS)
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE objectives ENABLE ROW LEVEL SECURITY;
ALTER TABLE routines ENABLE ROW LEVEL SECURITY;
ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE activity ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir todo a anon users" ON users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon objectives" ON objectives FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon routines" ON routines FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon tasks" ON tasks FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Permitir todo a anon activity" ON activity FOR ALL USING (true) WITH CHECK (true);

-- 7. HABILITAR TIEMPO REAL (REALTIME)
ALTER PUBLICATION supabase_realtime ADD TABLE tasks;
ALTER PUBLICATION supabase_realtime ADD TABLE objectives;
ALTER PUBLICATION supabase_realtime ADD TABLE activity;
